-- Read-only access for the BI tool. Run as ACCOUNTADMIN.
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS BI_READER;
GRANT ROLE BI_READER TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE BI_READER;
GRANT USAGE ON DATABASE ECOMMERCE_DB TO ROLE BI_READER;
GRANT USAGE ON SCHEMA ECOMMERCE_DB.MARTS TO ROLE BI_READER;

GRANT SELECT ON ALL TABLES IN SCHEMA ECOMMERCE_DB.MARTS TO ROLE BI_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA ECOMMERCE_DB.MARTS TO ROLE BI_READER;
GRANT SELECT ON ALL VIEWS IN SCHEMA ECOMMERCE_DB.MARTS TO ROLE BI_READER;
GRANT SELECT ON FUTURE VIEWS IN SCHEMA ECOMMERCE_DB.MARTS TO ROLE BI_READER;

CREATE USER IF NOT EXISTS BI_USER
  PASSWORD = '<choose-a-strong-password>' 
  DEFAULT_ROLE = BI_READER
  DEFAULT_WAREHOUSE = COMPUTE_WH
  MUST_CHANGE_PASSWORD = FALSE;

GRANT ROLE BI_READER TO USER BI_USER;